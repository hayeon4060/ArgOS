-- ArgOS 중앙 서버 DB 스키마 (공장 제어망)
-- 기준: ArgOS DB 설계(ERD) 화면 설계 반영본 (2026-11-16, 33개 테이블)
-- 중앙 서버가 쓰는 테이블만 만든다. 사용자·체크리스트·채팅·점검 등은 연계 서버 DB 몫.
-- 사용자(app_user)는 연계 DB에 있으므로 *_by 컬럼은 FK 없이 사용자 ID만 담는다.

-- ---------------------------------------------------------------
-- 파일
-- ---------------------------------------------------------------
CREATE TABLE file_asset (
    file_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(20)  NOT NULL CHECK (kind IN ('THERMAL', 'DOC_SCAN', 'FLOORPLAN', 'REPORT')),
    path         VARCHAR(500) NOT NULL,
    mime         VARCHAR(100),
    size_bytes   BIGINT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    sensor_id    BIGINT,                 -- 열화상 카메라(IR 센서). FK 는 sensor 생성 뒤에 건다
    captured_at  TIMESTAMPTZ,
    meta         JSONB
);

-- ---------------------------------------------------------------
-- 마스터: 사업장 → 공장 → 공정 → 설비 → 센서
-- ---------------------------------------------------------------
CREATE TABLE plant (
    plant_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(50)  NOT NULL UNIQUE,
    code         VARCHAR(20)  NOT NULL UNIQUE,
    address      VARCHAR(200),
    lat          DOUBLE PRECISION,
    lng          DOUBLE PRECISION,
    map_file_id  BIGINT REFERENCES file_asset (file_id)
);

CREATE TABLE factory (
    factory_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id     BIGINT      NOT NULL REFERENCES plant (plant_id),
    code         VARCHAR(20) NOT NULL,
    name         VARCHAR(50) NOT NULL,
    map_shape    JSONB,
    sort_order   INT         NOT NULL DEFAULT 0,
    UNIQUE (plant_id, code)
);

CREATE TABLE process (
    process_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factory_id        BIGINT      NOT NULL REFERENCES factory (factory_id),
    code              VARCHAR(20) NOT NULL,
    name              VARCHAR(50) NOT NULL,
    tag_prefix        VARCHAR(5),
    floorplan_file_id BIGINT REFERENCES file_asset (file_id),
    UNIQUE (factory_id, code)
);

CREATE TABLE equipment (
    equipment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id      BIGINT       NOT NULL REFERENCES process (process_id),
    code            VARCHAR(30)  NOT NULL,
    name            VARCHAR(50)  NOT NULL,
    pos_x           DOUBLE PRECISION,
    pos_y           DOUBLE PRECISION,
    equipment_type  VARCHAR(20),
    shape           VARCHAR(20),
    size_w          DOUBLE PRECISION,
    size_d          DOUBLE PRECISION,
    size_h          DOUBLE PRECISION,
    pos_z           DOUBLE PRECISION,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    run_state       VARCHAR(10)  NOT NULL DEFAULT 'RUN' CHECK (run_state IN ('RUN', 'STOPPING', 'STOPPED')),
    fan_rpm         INT,
    UNIQUE (process_id, code)
);

CREATE TABLE sensor (
    sensor_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag           VARCHAR(20)  NOT NULL UNIQUE,
    equipment_id  BIGINT       NOT NULL REFERENCES equipment (equipment_id),
    sensor_type   VARCHAR(2)   NOT NULL CHECK (sensor_type IN ('TE', 'IT', 'AT', 'IR')),
    unit          VARCHAR(10),
    connection    VARCHAR(5)   CHECK (connection IN ('PLC', 'GW', 'VMS')),
    sample_sec    INT          NOT NULL DEFAULT 5,
    setpoint      DOUBLE PRECISION,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);

ALTER TABLE file_asset
    ADD CONSTRAINT fk_file_asset_sensor FOREIGN KEY (sensor_id) REFERENCES sensor (sensor_id);

-- 관제 단위: 판정을 묶는 단위 (예: 전착 건조로 = 건조로 온도 + 배기팬 전류 + 버너실 CO)
CREATE TABLE control_unit (
    unit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id    BIGINT      NOT NULL REFERENCES process (process_id),
    equipment_id  BIGINT      REFERENCES equipment (equipment_id),
    name          VARCHAR(50) NOT NULL,
    is_active     BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE control_unit_sensor (
    unit_id    BIGINT     NOT NULL REFERENCES control_unit (unit_id),
    sensor_id  BIGINT     NOT NULL REFERENCES sensor (sensor_id),
    hazard     VARCHAR(4) NOT NULL CHECK (hazard IN ('FIRE', 'GAS')),
    PRIMARY KEY (unit_id, sensor_id, hazard)
);

-- ---------------------------------------------------------------
-- 기준값 · 시계열 · 이벤트
-- ---------------------------------------------------------------
CREATE TABLE sensor_threshold (
    threshold_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id      BIGINT      NOT NULL REFERENCES sensor (sensor_id),
    warn_value     DOUBLE PRECISION,           -- 2단계(주의) 상한
    alarm_value    DOUBLE PRECISION,           -- 3단계(경보) 상한
    low_warn       DOUBLE PRECISION,           -- 2단계 하한 (전류처럼 양방향 감시)
    low_alarm      DOUBLE PRECISION,           -- 3단계 하한
    rate_per_min   DOUBLE PRECISION,           -- 지금 규칙에서는 비워 둠
    warn_samples   INT         NOT NULL DEFAULT 24,
    alarm_samples  INT         NOT NULL DEFAULT 6,
    basis          VARCHAR(10) NOT NULL DEFAULT 'PROPOSED' CHECK (basis IN ('STANDARD', 'PROPOSED')),
    note           VARCHAR(200),
    valid_from     TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_to       TIMESTAMPTZ,
    changed_by     BIGINT,                     -- 연계 DB app_user.user_id
    season         VARCHAR(12) NOT NULL DEFAULT 'ALL' CHECK (season IN ('ALL', 'SPRING_FALL', 'SUMMER', 'WINTER')),
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE INDEX ix_sensor_threshold_current ON sensor_threshold (sensor_id) WHERE valid_to IS NULL;

-- 1분 추이 (5초 값 12개를 평균·최소·최대로 줄인 값)
CREATE TABLE sensor_trend (
    sensor_id  BIGINT      NOT NULL REFERENCES sensor (sensor_id),
    ts         TIMESTAMPTZ NOT NULL,
    avg_v      DOUBLE PRECISION NOT NULL,
    min_v      DOUBLE PRECISION NOT NULL,
    max_v      DOUBLE PRECISION NOT NULL,
    n          INT         NOT NULL,
    PRIMARY KEY (sensor_id, ts)
);

-- 임계값 초과 구간
CREATE TABLE sensor_event (
    event_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id     BIGINT      NOT NULL REFERENCES sensor (sensor_id),
    threshold_id  BIGINT      REFERENCES sensor_threshold (threshold_id),
    stage         SMALLINT    NOT NULL CHECK (stage IN (2, 3)),
    rule          VARCHAR(10) NOT NULL DEFAULT 'DURATION' CHECK (rule IN ('ABS', 'RATE', 'DURATION', 'COMPOUND')),
    started_at    TIMESTAMPTZ NOT NULL,
    ended_at      TIMESTAMPTZ,
    peak_value    DOUBLE PRECISION,
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE INDEX ix_sensor_event_sensor_started ON sensor_event (sensor_id, started_at);
CREATE INDEX ix_sensor_event_open ON sensor_event (sensor_id) WHERE ended_at IS NULL;

-- 이벤트 구간의 5초 원시값
CREATE TABLE sensor_event_sample (
    event_id  BIGINT      NOT NULL REFERENCES sensor_event (event_id) ON DELETE CASCADE,
    ts        TIMESTAMPTZ NOT NULL,
    value     DOUBLE PRECISION,
    PRIMARY KEY (event_id, ts)
);

-- ---------------------------------------------------------------
-- 경보 · 명령
-- ---------------------------------------------------------------
CREATE TABLE alarm (
    alarm_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id       BIGINT      NOT NULL REFERENCES control_unit (unit_id),
    stage         SMALLINT    NOT NULL CHECK (stage IN (2, 3)),
    hazard        VARCHAR(4)  NOT NULL CHECK (hazard IN ('FIRE', 'GAS')),
    thermal_file  BIGINT      REFERENCES file_asset (file_id),
    raised_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    status        VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'ACKED', 'ACTING', 'CLOSED')),
    acked_by      BIGINT,
    acked_at      TIMESTAMPTZ,
    closed_at     TIMESTAMPTZ,
    closed_by     BIGINT
);
CREATE INDEX ix_alarm_raised ON alarm (raised_at);
CREATE INDEX ix_alarm_unit_status ON alarm (unit_id, status);

-- 경보 판정 근거 (경보 ↔ 원인 센서 이벤트)
CREATE TABLE alarm_event (
    alarm_id  BIGINT NOT NULL REFERENCES alarm (alarm_id) ON DELETE CASCADE,
    event_id  BIGINT NOT NULL REFERENCES sensor_event (event_id) ON DELETE CASCADE,
    PRIMARY KEY (alarm_id, event_id)
);

CREATE TABLE equipment_command (
    command_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id  BIGINT      NOT NULL REFERENCES equipment (equipment_id),
    alarm_id      BIGINT      REFERENCES alarm (alarm_id),
    command       VARCHAR(10) NOT NULL CHECK (command IN ('FAN_ON', 'FAN_OFF', 'FAN_RPM', 'SHUTDOWN', 'RESTART')),
    value         DOUBLE PRECISION,
    result        VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (result IN ('PENDING', 'OK', 'FAIL')),
    requested_by  BIGINT,
    requested_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at  TIMESTAMPTZ
);
