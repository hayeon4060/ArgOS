-- 파일 (점검 서류 스캔 · 배치도 · 보고서). 열화상 사진은 수집 서버 file_asset 에 있다.
CREATE TABLE IF NOT EXISTS file_asset (
    file_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(12) NOT NULL CHECK (kind IN ('DOC_SCAN', 'FLOORPLAN', 'REPORT')),
    path        VARCHAR(300) NOT NULL,
    mime        VARCHAR(50),
    size_bytes  BIGINT,
    orig_name   VARCHAR(200),
    meta        JSONB,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 설비 담당자 (H1 설비 정보의 담당자). 설비는 수집 서버 DB 에 있어 FK 없음
CREATE TABLE IF NOT EXISTS equipment_manager (
    equipment_id BIGINT NOT NULL,
    user_id      BIGINT NOT NULL REFERENCES app_user(user_id),
    is_primary   BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (equipment_id, user_id)
);

-- 서류 양식 F01~F05
CREATE TABLE IF NOT EXISTS doc_form (
    form_type    VARCHAR(4) PRIMARY KEY,
    name         VARCHAR(50) NOT NULL,
    field_schema JSONB NOT NULL,
    version      SMALLINT NOT NULL DEFAULT 1
);

-- 점검 일정 (equipment_id 는 수집 서버 설비 id)
CREATE TABLE IF NOT EXISTS inspection_schedule (
    schedule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT NOT NULL,
    process_id  BIGINT,
    assignee_id BIGINT REFERENCES app_user(user_id),
    planned_at  DATE NOT NULL,
    planned_time TIME,
    form_type   VARCHAR(4) REFERENCES doc_form(form_type),
    status      VARCHAR(10) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'DONE', 'OVERDUE')),
    title       VARCHAR(100) NOT NULL,
    done_at     TIMESTAMPTZ,
    done_by     BIGINT REFERENCES app_user(user_id)
);
CREATE INDEX IF NOT EXISTS idx_schedule_day ON inspection_schedule(planned_at);

-- 서류 인식 결과
CREATE TABLE IF NOT EXISTS ocr_result (
    ocr_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT REFERENCES inspection_schedule(schedule_id),
    file_id     BIGINT NOT NULL REFERENCES file_asset(file_id),
    form_type   VARCHAR(4) REFERENCES doc_form(form_type),
    fields      JSONB,
    confidence  DOUBLE PRECISION,
    status      VARCHAR(12) NOT NULL DEFAULT 'UPLOADED'
                CHECK (status IN ('UPLOADED', 'RECOGNIZING', 'REVIEW', 'DONE', 'FAILED')),
    reviewed_by BIGINT REFERENCES app_user(user_id),
    reviewed_at TIMESTAMPTZ,
    uploaded_by BIGINT NOT NULL REFERENCES app_user(user_id),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    process_id  BIGINT
);
CREATE INDEX IF NOT EXISTS idx_ocr_uploaded ON ocr_result(uploaded_at DESC);

-- 공장 월별 안전 등급 (보고서용)
CREATE TABLE IF NOT EXISTS safety_grade (
    factory_id BIGINT NOT NULL,
    month      DATE NOT NULL,
    grade      CHAR(1) NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    score      DOUBLE PRECISION,
    PRIMARY KEY (factory_id, month)
);

