-- 채팅 (명세서 I2): 사업장 하나가 대화방 하나 (roomId = plant_id)
CREATE TABLE IF NOT EXISTS chat_message (
    msg_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id    BIGINT NOT NULL,
    sender_id   BIGINT NOT NULL REFERENCES app_user(user_id),
    body        VARCHAR(1000) NOT NULL,
    alarm_id    BIGINT,
    schedule_id BIGINT,
    sent_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_chat_message_room ON chat_message(plant_id, msg_id DESC);

CREATE TABLE IF NOT EXISTS chat_read (
    user_id     BIGINT NOT NULL REFERENCES app_user(user_id),
    plant_id    BIGINT NOT NULL,
    last_msg_id BIGINT NOT NULL DEFAULT 0,
    read_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, plant_id)
);

-- 화재 대응 (명세서 C4F · C5). 화재 경보 하나에 한 건
CREATE TABLE IF NOT EXISTS fire_incident (
    fire_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id             BIGINT NOT NULL UNIQUE,
    plant_id             BIGINT NOT NULL,
    process_id           BIGINT,
    equipment_id         BIGINT,
    pos_x                DOUBLE PRECISION,
    pos_y                DOUBLE PRECISION,
    max_temp             DOUBLE PRECISION,
    detected_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    broadcast_started_at TIMESTAMPTZ,
    broadcast_ended_at   TIMESTAMPTZ,
    hq_notified_at       TIMESTAMPTZ,
    unlock_fail_count    SMALLINT NOT NULL DEFAULT 0,
    status               VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLEARED')),
    cleared_by           BIGINT REFERENCES app_user(user_id),
    cleared_at           TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_fire_status ON fire_incident(status, detected_at DESC);
