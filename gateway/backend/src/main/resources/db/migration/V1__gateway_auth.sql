-- 연계 PC 인증에 필요한 최소 테이블. 사업장·공장·공정 마스터는 별도 도메인 마이그레이션에서 관리한다.
CREATE TABLE IF NOT EXISTS role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL
);

INSERT INTO role (code, name) VALUES
    ('HQ_ADMIN', '본사 관리자'),
    ('PLANT_ADMIN', '공장 담당자'),
    ('WORKER', '공정 담당자')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE IF NOT EXISTS app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT,
    role_id BIGINT NOT NULL REFERENCES role(role_id),
    login_id VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(30),
    fcm_token TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    pw_reset_required BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_assignment (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    plant_id BIGINT,
    factory_id BIGINT,
    process_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_user_assignment_user ON user_assignment(user_id);

CREATE TABLE IF NOT EXISTS login_history (
    login_id_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_user(user_id),
    logged_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ip_addr VARCHAR(64),
    success BOOLEAN NOT NULL,
    attempted_login_id VARCHAR(100),
    failure_code VARCHAR(40)
);
-- 존재하지 않는 아이디의 실패도 기록하기 위한 보완 컬럼이다.
ALTER TABLE login_history ADD COLUMN IF NOT EXISTS attempted_login_id VARCHAR(100);
ALTER TABLE login_history ADD COLUMN IF NOT EXISTS failure_code VARCHAR(40);
ALTER TABLE login_history ALTER COLUMN user_id DROP NOT NULL;
CREATE INDEX IF NOT EXISTS idx_login_attempt ON login_history(attempted_login_id, logged_at DESC);

CREATE TABLE IF NOT EXISTS auth_login_lock (
    login_id VARCHAR(100) PRIMARY KEY,
    locked_until TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS activity_log (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_user(user_id),
    plant_id BIGINT,
    process_id BIGINT,
    type VARCHAR(40) NOT NULL,
    target_table VARCHAR(80),
    target_id BIGINT,
    summary TEXT NOT NULL,
    before JSONB,
    after JSONB,
    ip_addr VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- JWT를 즉시 폐기하고 13시간 절대 만료를 적용하기 위한 서버 측 세션.
CREATE TABLE IF NOT EXISTS auth_refresh_session (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    client VARCHAR(10) NOT NULL CHECK (client IN ('WEB', 'APP')),
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_auth_session_user ON auth_refresh_session(user_id);
