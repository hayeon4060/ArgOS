-- 연계 DB: 경보 대응 (조치 이력, 체크리스트)
-- 기준: ArgOS DB 설계(ERD) 화면 설계 반영본 (2026-11-16)
-- 경보(alarm) 원본은 중앙 DB 에 있으므로 alarm_id 는 FK 없이 중앙 alarm.alarm_id 값을 담는다.

-- 경보 조치 이력: 경보 하나에 대해 한 일을 한 줄씩
CREATE TABLE IF NOT EXISTS alarm_action (
    action_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id   BIGINT       NOT NULL,                 -- 중앙 alarm.alarm_id
    action     VARCHAR(20)  NOT NULL CHECK (action IN
               ('PUSH', 'BROADCAST', 'SHUTDOWN', 'CHECKLIST', 'MANUAL_NOTE', 'ACK', 'REASSIGN', 'EVACUATED',
                'REPORT', 'CONFIRM', 'CLOSE', 'CALL', 'FAN')),
    target     VARCHAR(200),                          -- 푸시 대상, 설비, 방송 구역 등
    result     VARCHAR(10)  NOT NULL DEFAULT 'OK' CHECK (result IN ('OK', 'FAIL', 'PENDING')),
    detail     TEXT,
    user_id    BIGINT REFERENCES app_user (user_id),  -- 시스템 자동 조치는 NULL
    done_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_alarm_action_alarm ON alarm_action (alarm_id, done_at);

-- 체크리스트 양식: 설비 종류 · 센서 종류별 원인 문구와 항목
CREATE TABLE IF NOT EXISTS checklist_template (
    template_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_type  VARCHAR(20)  NOT NULL,            -- 중앙 equipment.equipment_type (FAN, OVEN, BURNER …)
    sensor_type     VARCHAR(2)   NOT NULL CHECK (sensor_type IN ('TE', 'IT', 'AT', 'IR')),
    stage           SMALLINT     NOT NULL DEFAULT 2 CHECK (stage IN (2, 3)),
    cause           VARCHAR(200) NOT NULL,
    items           JSONB        NOT NULL,            -- ["항목 1", "항목 2", …]
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE
);

-- 체크리스트: 주의 때 공정 담당자 앱으로 보낸 한 건
CREATE TABLE IF NOT EXISTS checklist (
    checklist_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id        BIGINT       NOT NULL,            -- 중앙 alarm.alarm_id
    template_id     BIGINT REFERENCES checklist_template (template_id),
    assignee_id     BIGINT       NOT NULL REFERENCES app_user (user_id),
    status          VARCHAR(12)  NOT NULL DEFAULT 'SENT'
                    CHECK (status IN ('SENT', 'IN_PROGRESS', 'REPORTED', 'CONFIRMED', 'CANCELLED')),
    sent_by         BIGINT REFERENCES app_user (user_id),
    sent_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    remind_count    INT          NOT NULL DEFAULT 0,
    last_remind_at  TIMESTAMPTZ,
    reported_at     TIMESTAMPTZ,
    confirmed_by    BIGINT REFERENCES app_user (user_id),
    confirmed_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_checklist_alarm ON checklist (alarm_id);
CREATE INDEX IF NOT EXISTS idx_checklist_assignee ON checklist (assignee_id, status);

CREATE TABLE IF NOT EXISTS checklist_item (
    item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id  BIGINT       NOT NULL REFERENCES checklist (checklist_id) ON DELETE CASCADE,
    seq           INT          NOT NULL,
    content       VARCHAR(300) NOT NULL,
    done_at       TIMESTAMPTZ,
    result        VARCHAR(30),                        -- 이상 없음 / 조치함 / 부품 교체 예정 / 추가 점검 필요
    memo          VARCHAR(300),
    UNIQUE (checklist_id, seq)
);

